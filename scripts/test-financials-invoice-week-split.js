#!/usr/bin/env node
/**
 * Money plan C (2026-10-15): a weekly driver invoice whose Saturday-to-Friday
 * week spans two months is counted in full in BOTH months of the Financials
 * month detail's driver table (GET /api/financials?month=, "Invoiced",
 * "Adjustments", "Variance" and the invoice count).
 *
 * Written before the fix, which every case but the C4 control failed: the table read
 * every live invoice with `week_start <= monthEnd AND week_end >= monthStart`
 * and adds each one's whole total_earnings + adjustment + personal_share_total
 * to every month it touches, while the driver pay beside it is the ledger's,
 * one day in one month. So W39 (Sat 9/26 - Fri 10/2) shows its full amount in
 * September and again in October, and each month's variance is off by the
 * other month's share.
 *
 * The contract these cases pin (plan C, recommendations C-D1 to C-D3):
 *   - each paid day on the invoice counts in the month the Financials books
 *     count that driver-day in (a closed month's FROZEN items, an open
 *     month's live ledger: the load's Assigned month); a day the books count
 *     in two months goes to the earliest of them (the ledger day-once rule's
 *     tie-break); a day the books do not pay counts in its own month (C-D1 a);
 *   - an owner-operator invoice splits by render_data.loads, each load's share
 *     of the earnings (by its rate) in that load's month in the books;
 *   - an invoice with no day grid is prorated by the week's calendar days
 *     (C-D3); cents rounding goes to the last month;
 *   - the adjustment, an owner-operator's returned Personal share and any gap
 *     between the day grid and total_earnings count once, in the month of
 *     week_end (C-D2); a gap is never spread as rounding;
 *   - the invoice count counts the invoice in each month holding a share;
 *   - no settled figure (revenue, driver pay, payouts) changes: only the
 *     invoiced, adjustments and variance columns and the count, closed months
 *     included (C-D4 a).
 * C4 (a week inside one month) is the control and passed before the fix too.
 * Added with the fix, and failing before it: C10, a day the books pay in a
 * month the invoice's week does not touch (a load assigned the month before its
 * pickup) counts in that month; C11, a manual invoice that names its days counts
 * each day at the amount of its line dated that day; C12, a day grid is read by
 * each day's place in it from week_start, also when week_start is no Saturday.
 *
 * The weekly invoice is generated by generateInvoiceHandler() and the page is
 * GET /api/financials, both lifted from server.js
 * (scripts/lib/money-plans-world.js). Made-up data only: one driver at $300 a
 * day. Pure: no server, no app.db, no network.
 *
 * Run: node scripts/test-financials-invoice-week-split.js    # exits 1 on failure
 */
"use strict";
process.env.TZ = "UTC"; // production's clock zone

const fs = require("fs");
const path = require("path");
function findRoot(dir) {
	while (!fs.existsSync(path.join(dir, "server.js"))) {
		const up = path.dirname(dir);
		if (up === dir) throw new Error("server.js not found above this runner");
		dir = up;
	}
	return dir;
}
const M = require(path.join(findRoot(__dirname), "scripts", "lib", "money-plans-world.js"));
const { loadRow } = M;

const AMY = "Amy Birch";
const NOW = Date.parse("2026-10-20T16:00:00Z");

function world(rows) {
	return M.startWorld({ drivers: [{ name: AMY, payDaily: 300 }], rows, now: NOW });
}
// Two loads in W39: Sep-assigned 9/28-9/29 and Oct-assigned 10/1-10/2.
const W39 = [
	loadRow({ id: "C101", driver: AMY, pickup: "2026-09-28 8:00", dropoff: "2026-09-29 18:00", assigned: "2026-09-28", done: "2026-09-29", truck: "T1" }),
	loadRow({ id: "C102", driver: AMY, pickup: "2026-10-01 8:00", dropoff: "2026-10-02 18:00", assigned: "2026-10-01", done: "2026-10-02", truck: "T1" }),
];
async function driverRow(w, month) {
	const r = await M.route(w, "GET /api/financials", { query: { month } });
	if (r.status !== 200) throw new Error(`GET /api/financials?month=${month}: ${r.status}`);
	const row = (r.body.monthDetail.drivers || []).find((d) => d.name === AMY) || null;
	return row && { pay: row.pay, invoiceCount: row.invoiceCount, invoicedTotal: row.invoicedTotal, adjustments: row.adjustments, variance: row.variance };
}

const R = M.createRunner("Money plan C: an invoice week spanning two months is split between them in the Financials driver table");

(async () => {
	await R.test("C1 W39 ($1,200: 9/28, 9/29, 10/1, 10/2): September shows $600 invoiced against $600 pay, October $600 against $600. Base: $1,200 in each, variance +$600", async ({ eq }) => {
		const w = world(W39);
		const g = await M.generate(w, AMY, "2026-10-02");
		eq("invoice generated for $1,200", [g.status, g.invoice && g.invoice.total_earnings], [200, 1200]);
		eq("September", await driverRow(w, "2026-09"), { pay: 600, invoiceCount: 1, invoicedTotal: 600, adjustments: 0, variance: 0 });
		eq("October", await driverRow(w, "2026-10"), { pay: 600, invoiceCount: 1, invoicedTotal: 600, adjustments: 0, variance: 0 });
	});

	await R.test("C2 A +$100 adjustment on W39 counts once, in the month of week_end (October). Base: in both months", async ({ eq }) => {
		const w = world(W39);
		const g = await M.generate(w, AMY, "2026-10-02");
		w.db.prepare("UPDATE invoices SET adjustment = 100 WHERE id = ?").run(g.invoice.id);
		eq("September", await driverRow(w, "2026-09"), { pay: 600, invoiceCount: 1, invoicedTotal: 600, adjustments: 0, variance: 0 });
		eq("October", await driverRow(w, "2026-10"), { pay: 600, invoiceCount: 1, invoicedTotal: 700, adjustments: 100, variance: 100 });
	});

	await R.test("C3 A day the ledger counts in the load's Assigned month follows it: a Sep-assigned load 9/30-10/2 puts 10/1 and 10/2 in September with the ledger (all $900 in September, $0 in October). Base: $900 in both", async ({ eq }) => {
		const w = world([loadRow({ id: "C301", driver: AMY, pickup: "2026-09-30 8:00", dropoff: "2026-10-02 18:00", assigned: "2026-09-30", done: "2026-10-02", truck: "T1" })]);
		const g = await M.generate(w, AMY, "2026-10-02");
		eq("invoice generated for $900", [g.status, g.invoice && g.invoice.total_earnings], [200, 900]);
		eq("September", await driverRow(w, "2026-09"), { pay: 900, invoiceCount: 1, invoicedTotal: 900, adjustments: 0, variance: 0 });
		const oct = await driverRow(w, "2026-10");
		eq("October: no share, so no invoiced amount (no row, or a row at $0)", oct ? oct.invoicedTotal : 0, 0);
	});

	await R.test("C4 Control: a week inside one month (W41, 10/12-10/13, $600) counts once, in October, as today", async ({ eq }) => {
		const w = world([loadRow({ id: "C401", driver: AMY, pickup: "2026-10-12 8:00", dropoff: "2026-10-13 18:00", assigned: "2026-10-12", done: "2026-10-13", truck: "T1" })]);
		await M.generate(w, AMY, "2026-10-16");
		eq("October", await driverRow(w, "2026-10"), { pay: 600, invoiceCount: 1, invoicedTotal: 600, adjustments: 0, variance: 0 });
		eq("September: no row", await driverRow(w, "2026-09"), null);
	});

	await R.test("C5 The split adds up: September's and October's invoiced amounts count the invoice once (earnings $1,200 + $100 adjustment = $1,300). Base: $2,600", async ({ eq }) => {
		const w = world(W39);
		const g = await M.generate(w, AMY, "2026-10-02");
		w.db.prepare("UPDATE invoices SET adjustment = 100 WHERE id = ?").run(g.invoice.id);
		const sep = await driverRow(w, "2026-09");
		const oct = await driverRow(w, "2026-10");
		eq("sum of the two months", Math.round(((sep ? sep.invoicedTotal : 0) + (oct ? oct.invoicedTotal : 0)) * 100) / 100, 1300);
	});

	await R.test("C6 (C-D4 a, tie-break) A closed month reads its FROZEN items: September frozen with 9/28-9/29 in it, then the Sep load re-dated to October in the sheet. September: $600 invoiced against its frozen $600; October: only 10/1-10/2 ($600), because a day the books count in two months (frozen Sep, live Oct) goes to the earliest. Base: $1,200 in both", async ({ eq }) => {
		const w = world(W39);
		const g = await M.generate(w, AMY, "2026-10-02");
		eq("invoice generated for $1,200", [g.status, g.invoice && g.invoice.total_earnings], [200, 1200]);
		await M.freezeAndLock(w, "2026-09", "2026-10-15T04:00:00.000Z");
		w.setRow("C101", { "Assigned Date": M.md("2026-10-01") });
		eq("September (closed, frozen)", await driverRow(w, "2026-09"), { pay: 600, invoiceCount: 1, invoicedTotal: 600, adjustments: 0, variance: 0 });
		const oct = await driverRow(w, "2026-10");
		eq("October: live pay counts 9/28-10/2 ($1,200); invoiced only its own share", oct && [oct.pay, oct.invoicedTotal, oct.variance], [1200, 600, -600]);
	});

	await R.test("C7 (C-D3) An invoice with no day grid (W39, $1,500, render_data {}) is prorated by the week's calendar days: 5 in September ($1,071.43), 2 in October ($428.57). Base: $1,500 in both", async ({ eq }) => {
		const w = world(W39);
		M.insertInvoice(w.db, { invoice_number: "INV-AB-2026W39-01", driver: AMY, week_start: "2026-09-26", week_end: "2026-10-02", status: "Approved", total_earnings: 1500, render_data: "{}" });
		const sep = await driverRow(w, "2026-09");
		const oct = await driverRow(w, "2026-10");
		eq("invoiced by month", [sep && sep.invoicedTotal, oct && oct.invoicedTotal], [1071.43, 428.57]);
	});

	await R.test("C8 An owner-operator invoice (30% of $3,000 = $900) splits by render_data.loads: the Sep-assigned $2,000 load's share ($600) in September, the Oct-assigned $1,000 load's ($300) in October, matching the ledger's percentage pay. Base: $900 in both", async ({ eq }) => {
		const BO = "Bo Cole";
		const w = M.startWorld({
			drivers: [{ name: BO, payType: "percentage", payPct: 30 }], now: NOW,
			rows: [
				loadRow({ id: "C801", driver: BO, pickup: "2026-09-28 8:00", dropoff: "2026-09-29 18:00", assigned: "2026-09-28", done: "2026-09-29", truck: "T1", payment: "$2,000.00" }),
				loadRow({ id: "C802", driver: BO, pickup: "2026-10-01 8:00", dropoff: "2026-10-02 18:00", assigned: "2026-10-01", done: "2026-10-02", truck: "T1", payment: "$1,000.00" }),
			],
		});
		const g = await M.generate(w, BO, "2026-10-02");
		eq("invoice generated for $900", [g.status, g.invoice && g.invoice.total_earnings], [200, 900]);
		const pick = async (month) => {
			const r = await M.route(w, "GET /api/financials", { query: { month } });
			const d = (r.body.monthDetail.drivers || []).find((x) => x.name === BO) || null;
			return d && [d.pay, d.invoicedTotal, d.variance];
		};
		eq("September [pay, invoiced, variance]", await pick("2026-09"), [600, 600, 0]);
		eq("October [pay, invoiced, variance]", await pick("2026-10"), [300, 300, 0]);
	});

	await R.test("C9 A gap between the day grid ($1,200) and total_earnings ($1,250) is not spread as rounding: it counts once, in week_end's month (October), with the grid's days where the ledger counts them. Base: $1,250 in both", async ({ eq }) => {
		const w = world(W39);
		const g = await M.generate(w, AMY, "2026-10-02");
		w.db.prepare("UPDATE invoices SET total_earnings = 1250 WHERE id = ?").run(g.invoice.id);
		const sep = await driverRow(w, "2026-09");
		const oct = await driverRow(w, "2026-10");
		eq("invoiced by month", [sep && sep.invoicedTotal, oct && oct.invoicedTotal], [600, 650]);
	});

	await R.test("C10 A day the books pay in a month the week does not touch counts there: a load assigned 9/25 and driven 10/5-10/6 (W40, $600) is September's in the books, so September shows the $600 against its $600 pay and October none. Base: September no invoice, October $600 against $0", async ({ eq }) => {
		const w = world([loadRow({ id: "C1001", driver: AMY, pickup: "2026-10-05 8:00", dropoff: "2026-10-06 18:00", assigned: "2026-09-25", done: "2026-10-06", truck: "T1" })]);
		const g = await M.generate(w, AMY, "2026-10-09");
		eq("invoice generated for $600", [g.status, g.invoice && g.invoice.total_earnings], [200, 600]);
		eq("September", await driverRow(w, "2026-09"), { pay: 600, invoiceCount: 1, invoicedTotal: 600, adjustments: 0, variance: 0 });
		const oct = await driverRow(w, "2026-10");
		eq("October: no share, so no invoiced amount (no row, or a row at $0)", oct ? oct.invoicedTotal : 0, 0);
	});

	await R.test("C11 A manual invoice that names its days (paidDays 9/30 and 10/1, a $300 line dated each) counts each day at its line: 9/30, which the books do not pay, in September; 10/1 where the books pay it (October). Base: $600 in both", async ({ eq }) => {
		const w = world(W39);
		const snap = {
			__templateName: "service_invoice_manual", payeeName: AMY, paidDays: ["2026-09-30", "2026-10-01"],
			lineItems: [{ date: "2026-09-30", description: "Day worked", amount: 300 }, { date: "2026-10-01", description: "Day worked", amount: 300 }],
			deductions: [], subtotal: 600, deductionsTotal: 0, totalDue: 600,
		};
		M.insertInvoice(w.db, { invoice_number: "INV-M-AB-2026W39-01", driver: AMY.toLowerCase(), is_manual: 1, total_earnings: 600, loads_count: 2, rate_per_load: 0, render_data: JSON.stringify(snap) });
		const sep = await driverRow(w, "2026-09");
		const oct = await driverRow(w, "2026-10");
		eq("invoiced by month", [sep && sep.invoicedTotal, oct && oct.invoicedTotal], [300, 300]);
	});

	await R.test("C12 A weekly day grid whose week_start is not a Saturday (Sun 9/27-Sat 10/3; 9/27 and 10/1 paid, $150 each) reads each day by its place in the grid, as the invoice's days are read: $150 in September, $150 in October. A lookup by weekday name would find $0 days and put all $300 in October. Base: $300 in both", async ({ eq }) => {
		const w = world([]);
		const snap = { __templateName: "service_invoice", days: M.dayGrid("2026-09-27", ["2026-09-27", "2026-10-01"], 150), totalDue: 300 };
		M.insertInvoice(w.db, { invoice_number: "INV-AB-2026W39-02", driver: AMY.toLowerCase(), week_start: "2026-09-27", week_end: "2026-10-03", total_earnings: 300, loads_count: 2, rate_per_load: 150, render_data: JSON.stringify(snap) });
		const sep = await driverRow(w, "2026-09");
		const oct = await driverRow(w, "2026-10");
		eq("invoiced by month", [sep && sep.invoicedTotal, oct && oct.invoicedTotal], [150, 150]);
	});

	R.finish();
})();
